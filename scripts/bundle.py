#!/usr/bin/env python3
"""Concatenate every rule under python/ into eyalsec-python.yaml.

    python3 scripts/bundle.py          # rewrite the bundle
    python3 scripts/bundle.py --check  # exit 1 if the bundle is out of date
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BUNDLE = ROOT / "eyalsec-python.yaml"


def build() -> str:
    out = ["# Generated by scripts/bundle.py from python/**/*.yaml. Do not edit by hand.\n",
           "rules:\n"]
    for path in sorted((ROOT / "python").rglob("*.yaml")):
        text = path.read_text()
        if not text.startswith("rules:\n"):
            sys.exit(f"{path}: expected the file to start with 'rules:'")
        out.append(f"# {path.relative_to(ROOT)}\n")
        out.append(text[len("rules:\n"):])
    return "".join(out)


def main() -> None:
    text = build()
    if "--check" in sys.argv:
        if not BUNDLE.exists() or BUNDLE.read_text() != text:
            sys.exit("eyalsec-python.yaml is out of date: run python3 scripts/bundle.py")
        print("bundle is up to date")
        return
    BUNDLE.write_text(text)
    print(f"wrote {BUNDLE.name}")


main()
